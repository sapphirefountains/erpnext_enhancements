"""The Products tab's rules (v1.824.0): what is a product order, and which stage it is in.

Nikolas, 2026-11-18 (vault decisions/2026-11-18-estop-product-line.md): a product sale is a
Sales Order. The Projects Dashboard's Products tab shows those orders by stage (Ordered / Paid ->
Building -> Testing -> Ready -> Delivered), the product pipeline, stock and shortages, and the
control panel projects. ``erpnext_enhancements/product_orders.py`` holds every rule the tab's
endpoint applies, with no Frappe in it, so this suite runs bench-free.

What goes wrong without these checks, concretely:

* the ``PDT-`` rule written the obvious way puts every service quote on the tab: PDT-0701
  ("SERVICE - FOUNTAIN MATERIALS & EQUIPMENT") is on 325 invoice lines on prod and PDT-0400
  (chemicals) on 178;
* trusting the item group "Configured Products" puts a first aid kit and a heat exchanger on the
  board: prod has 13 hand-made Items in that group and none generated by the configurator;
* a unit built for one order is counted again as shelf stock for the next, and both read Ready;
* the tab's win rate and the Value Stream Performance report's drift apart;
* the script's lists of lines and stages stop matching the server's, and a chip filters on a
  line no row carries.

Run: python -m unittest erpnext_enhancements.tests.test_product_orders
"""

import ast
import re
import unittest
from datetime import date
from pathlib import Path

from erpnext_enhancements import product_orders as po

APP = Path(__file__).resolve().parents[1]
BLOCK_JS = (APP / "custom_html_blocks" / "projects_dashboard.js").read_text(encoding="utf-8")
BLOCK_HTML = (APP / "custom_html_blocks" / "projects_dashboard.html").read_text(encoding="utf-8")
REPORT = APP / "kpi_dashboards" / "report" / "value_stream_performance" / "value_stream_performance.py"


def _js_list(name):
	match = re.search(r"const " + re.escape(name) + r" = \[([^\]]*)\]", BLOCK_JS)
	assert match is not None, name + " is gone from the block"
	return re.findall(r'"([^"]+)"', match.group(1))


def wo(status, docstatus=1, qty=1, produced=0):
	return {"status": status, "docstatus": docstatus, "qty": qty, "produced_qty": produced}


class TestProductLine(unittest.TestCase):
	"""Which Items are products, and their line. The codes are prod's, read on 2026-11-18."""

	def test_the_estop_and_every_configuration_of_it(self):
		for code in ("PDT-0040", "PDT-0040-1-1-1-2-0", "PDT-0040-3-2-3-3-3", "pdt-0040-1-1-1-2-0"):
			with self.subTest(code=code):
				self.assertEqual(po.product_line(code), po.LINE_ESTOPS)

	def test_the_control_panels_nikolas_listed(self):
		for code in (
			"PDT-0000",  # Splash Wizard Basic
			"PDT-0003",  # Splash Wizard Industrial
			"PDT-0017",  # the second Industrial item
			"PDT-0011",  # VFD Bypass 15 HP
			"PDT-0008 VFD BYPASS W/MOTOR PROTECTION, 5HP - copy",
			"PDT-0016",  # Pool & Fountain Center Pinnacle
			"PDT-0022",  # Level Master Wind & Water
			"PDT-0055",  # Activation Bollard
		):
			with self.subTest(code=code):
				self.assertEqual(po.product_line(code), po.LINE_PANELS)

	def test_the_other_products(self):
		for code in ("PDT-0151", "PDT-0050", "PDT-0263", "PDT-0551"):
			with self.subTest(code=code):
				self.assertEqual(po.product_line(code), po.LINE_OTHER)

	def test_sapphire_connect_hardware_is_a_product(self):
		# PDT-0030 "BUILD - SAPPHIRE CONNECT HARDWARE" reads like a billing catch-all, but
		# Nikolas ruled on 2026-11-18 that it is a product.
		self.assertEqual(po.product_line("PDT-0030"), po.LINE_OTHER)
		self.assertNotIn("0030", po.NOT_PRODUCT_FAMILIES)

	def test_the_billing_catch_alls_are_not_products(self):
		# PDT-0701 is on 325 invoice lines, PDT-0400 on 178: service work, not product sales.
		for code in ("PDT-0701", "PDT-0400"):
			with self.subTest(code=code):
				self.assertIsNone(po.product_line(code))
				self.assertFalse(po.is_product_item(code))

	def test_junk_and_deleted_codes_are_not_products(self):
		for code in ("PDT-00040 (deleted)", "PDT-00XX", "PDT-00051", "PDT-", "PDT0040", "", None):
			with self.subTest(code=code):
				self.assertIsNone(po.product_line(code))

	def test_the_configured_products_item_group_alone_makes_nothing_a_product(self):
		# Prod's 13 hand-made Items in that group: a first aid kit, a union, a heat exchanger.
		for code in ("H-6470", "8058-020", "VITODENS 200-W, B2HB 199", "FWS-100"):
			with self.subTest(code=code):
				self.assertIsNone(po.product_line(code, None))
				self.assertIsNone(po.product_line(code, ""))

	def test_an_item_the_configurator_made_is_a_product(self):
		self.assertEqual(po.product_line("PDT-0040-1-1-1-2-0", "CFG-0001"), po.LINE_ESTOPS)
		self.assertEqual(po.product_line("PDT-0003-X", "CFG-0002"), po.LINE_PANELS)
		# its code has no PDT family: still a product, in Other
		self.assertEqual(po.product_line("SW-CUSTOM-7", "CFG-0003"), po.LINE_OTHER)

	def test_the_families_do_not_overlap(self):
		self.assertFalse(po.ESTOP_FAMILIES & po.CONTROL_PANEL_FAMILIES)
		self.assertFalse(po.NOT_PRODUCT_FAMILIES & (po.ESTOP_FAMILIES | po.CONTROL_PANEL_FAMILIES))
		for family in po.ESTOP_FAMILIES | po.CONTROL_PANEL_FAMILIES | po.NOT_PRODUCT_FAMILIES:
			self.assertRegex(family, r"^\d{4}$")

	def test_lines_of_a_document_come_in_chip_order_once_each(self):
		items = [
			{"item_code": "PDT-0151"},
			{"item_code": "PDT-0701"},
			{"item_code": "PDT-0040-1-1-1-2-0"},
			{"item_code": "PDT-0040"},
		]
		self.assertEqual(po.lines_of(items), [po.LINE_ESTOPS, po.LINE_OTHER])
		self.assertEqual(po.lines_of([{"item_code": "PDT-0701"}]), [])
		self.assertEqual(po.lines_of([]), [])
		self.assertEqual(po.lines_of(None), [])

	def test_a_line_already_worked_out_is_kept(self):
		# The endpoint keeps each order line's `line` and drops the provenance before it answers.
		# Worked out again from the code alone, the configured Item below would have no line.
		self.assertEqual(po.lines_of([{"item_code": "SW-CUSTOM-7", "line": po.LINE_OTHER}]), [po.LINE_OTHER])
		self.assertEqual(
			po.lines_of([{"item_code": "SW-CUSTOM-7", "source_configuration": "CFG-1"}]), [po.LINE_OTHER]
		)
		self.assertEqual(po.lines_of([{"item_code": "PDT-0040", "line": "Nonsense"}]), [po.LINE_ESTOPS])


class TestOrderStage(unittest.TestCase):
	def test_sold_with_nothing_released_is_ordered(self):
		self.assertEqual(po.order_stage(0, []), {"stage": po.STAGE_ORDERED, "note": "No Work Order yet"})

	def test_a_draft_work_order_moves_nothing(self):
		stage = po.order_stage(0, [wo("Draft", docstatus=0)])
		self.assertEqual(stage["stage"], po.STAGE_ORDERED)
		self.assertEqual(stage["note"], "Work Order not submitted")

	def test_a_submitted_work_order_is_building(self):
		self.assertEqual(po.order_stage(0, [wo("Not Started")])["note"], "Work Order not started")
		self.assertEqual(po.order_stage(0, [wo("In Process")])["note"], "Work Order in process")
		self.assertEqual(
			po.order_stage(0, [wo("Not Started", qty=2, produced=1)])["note"], "Work Order in process"
		)
		self.assertEqual(po.order_stage(0, [wo("Stopped")])["note"], "Work Order stopped")
		for status in ("Not Started", "In Process", "Stopped", "Material Transferred"):
			with self.subTest(status=status):
				self.assertEqual(po.order_stage(0, [wo(status)])["stage"], po.STAGE_BUILDING)

	def test_one_unfinished_work_order_keeps_the_order_building(self):
		stage = po.order_stage(0, [wo("Completed", produced=1), wo("In Process")])
		self.assertEqual(stage["stage"], po.STAGE_BUILDING)

	def test_a_cancelled_work_order_is_ignored(self):
		self.assertEqual(po.order_stage(0, [wo("Cancelled", docstatus=2)])["stage"], po.STAGE_ORDERED)
		self.assertEqual(po.order_stage(0, [wo("Cancelled")])["stage"], po.STAGE_ORDERED)
		self.assertEqual(
			po.order_stage(0, [wo("Cancelled", docstatus=2), wo("Completed")])["stage"], po.STAGE_READY
		)

	def test_finished_work_orders_are_ready_while_the_test_is_not_recorded(self):
		for done in (wo("Completed", produced=1), wo("Closed"), wo("In Process", qty=2, produced=2)):
			with self.subTest(done=done):
				self.assertEqual(po.order_stage(0, [done]), {"stage": po.STAGE_READY, "note": "Built"})

	def test_stock_on_the_shelf_makes_an_order_without_a_work_order_ready(self):
		self.assertEqual(
			po.order_stage(0, [], stock_covered=True), {"stage": po.STAGE_READY, "note": "From stock"}
		)
		# a build in progress is still building, whatever the shelf holds
		self.assertEqual(
			po.order_stage(0, [wo("In Process")], stock_covered=True)["stage"], po.STAGE_BUILDING
		)

	def test_the_qc_hook_holds_a_built_unit_in_testing_until_it_passes(self):
		built = [wo("Completed", produced=1)]
		self.assertEqual(po.order_stage(0, built, qc=po.QC_PENDING)["stage"], po.STAGE_TESTING)
		self.assertEqual(
			po.order_stage(0, built, qc=po.QC_FAILED), {"stage": po.STAGE_TESTING, "note": "Test failed"}
		)
		self.assertEqual(po.order_stage(0, built, qc=po.QC_PASSED)["stage"], po.STAGE_READY)
		self.assertEqual(
			po.order_stage(0, [], stock_covered=True, qc=po.QC_PENDING)["stage"], po.STAGE_TESTING
		)
		# the test applies to a built unit only: an unbuilt order is not "testing"
		self.assertEqual(po.order_stage(0, [wo("In Process")], qc=po.QC_PENDING)["stage"], po.STAGE_BUILDING)
		self.assertEqual(po.order_stage(0, [], qc=po.QC_PENDING)["stage"], po.STAGE_ORDERED)

	def test_delivered_wins_over_everything(self):
		self.assertEqual(
			po.order_stage(100, [wo("In Process")], qc=po.QC_FAILED)["stage"], po.STAGE_DELIVERED
		)
		self.assertEqual(po.order_stage(100.0, [])["stage"], po.STAGE_DELIVERED)
		self.assertEqual(po.order_stage(99.9, [], stock_covered=True)["stage"], po.STAGE_READY)

	def test_missing_and_odd_values_do_not_raise(self):
		self.assertEqual(po.order_stage(None, None)["stage"], po.STAGE_ORDERED)
		self.assertEqual(po.order_stage("", [{"status": None, "docstatus": None}])["stage"], po.STAGE_ORDERED)
		self.assertEqual(
			po.order_stage("x", [wo("In Process", qty="2", produced="abc")])["stage"], po.STAGE_BUILDING
		)

	def test_every_stage_has_a_label_in_board_order(self):
		self.assertEqual(
			po.STAGES,
			(po.STAGE_ORDERED, po.STAGE_BUILDING, po.STAGE_TESTING, po.STAGE_READY, po.STAGE_DELIVERED),
		)
		self.assertEqual(set(po.STAGE_LABELS), set(po.STAGES))
		self.assertEqual(po.STAGE_LABELS[po.STAGE_ORDERED], "Ordered / Paid")


class TestAllocateStock(unittest.TestCase):
	def order(self, name, date_, code="PDT-0040-1-1-1-2-0", qty=1, built=False, has_wo=False):
		return {
			"name": name,
			"delivery_date": date_,
			"built": built,
			"has_work_order": has_wo,
			"lines": [{"item_code": code, "pending_qty": qty}],
		}

	def test_the_earliest_promise_is_covered_first(self):
		orders = [
			self.order("SO-2", "2026-12-10"),
			self.order("SO-1", "2026-12-01"),
			self.order("SO-3", None),
		]
		self.assertEqual(po.allocate_stock(orders, {"PDT-0040-1-1-1-2-0": 2}), {"SO-1", "SO-2"})
		self.assertEqual(po.allocate_stock(orders, {"PDT-0040-1-1-1-2-0": 1}), {"SO-1"})
		self.assertEqual(po.allocate_stock(orders, {}), set())

	def test_a_unit_built_for_one_order_never_covers_another(self):
		# SO-1 was built to order: its unit is on the shelf until it ships, and it is SO-1's.
		orders = [self.order("SO-1", "2026-12-20", built=True, has_wo=True), self.order("SO-2", "2026-12-01")]
		self.assertEqual(po.allocate_stock(orders, {"PDT-0040-1-1-1-2-0": 1}), set())
		self.assertEqual(po.allocate_stock(orders, {"PDT-0040-1-1-1-2-0": 2}), {"SO-2"})

	def test_an_order_still_being_built_claims_nothing(self):
		orders = [self.order("SO-1", "2026-11-01", has_wo=True), self.order("SO-2", "2026-12-01")]
		self.assertEqual(po.allocate_stock(orders, {"PDT-0040-1-1-1-2-0": 1}), {"SO-2"})

	def test_an_order_is_covered_only_when_every_line_is(self):
		mixed = {
			"name": "SO-1",
			"delivery_date": "2026-12-01",
			"lines": [
				{"item_code": "PDT-0040-1-1-1-2-0", "pending_qty": 1},
				{"item_code": "PDT-0040-2-1-0-0-0", "pending_qty": 1},
			],
		}
		self.assertEqual(po.allocate_stock([mixed], {"PDT-0040-1-1-1-2-0": 5}), set())
		self.assertEqual(
			po.allocate_stock([mixed], {"PDT-0040-1-1-1-2-0": 1, "PDT-0040-2-1-0-0-0": 1}), {"SO-1"}
		)

	def test_a_short_shelf_is_not_spent_on_a_partial_cover(self):
		# SO-1 needs 3 and the shelf has 2: SO-1 is not covered, and the 2 still cover SO-2.
		orders = [self.order("SO-1", "2026-12-01", qty=3), self.order("SO-2", "2026-12-05", qty=2)]
		self.assertEqual(po.allocate_stock(orders, {"PDT-0040-1-1-1-2-0": 2}), {"SO-2"})

	def test_a_fully_delivered_order_claims_nothing(self):
		orders = [self.order("SO-1", "2026-12-01", qty=0)]
		self.assertEqual(po.allocate_stock(orders, {"PDT-0040-1-1-1-2-0": 3}), set())

	def test_dates_may_be_dates(self):
		orders = [self.order("SO-2", date(2026, 12, 10)), self.order("SO-1", date(2026, 12, 1))]
		self.assertEqual(po.allocate_stock(orders, {"PDT-0040-1-1-1-2-0": 1}), {"SO-1"})


class TestSmallFacts(unittest.TestCase):
	def test_paid_state(self):
		self.assertEqual(po.paid_state(0, 0, 0), "not_invoiced")
		self.assertEqual(po.paid_state(None, None, None), "not_invoiced")
		self.assertEqual(po.paid_state(2005.24, 0, 100), "paid")
		self.assertEqual(po.paid_state(2005.24, 0.001, 100), "paid")
		self.assertEqual(po.paid_state(1000, 0, 50), "part_paid")  # all that is billed is paid
		self.assertEqual(po.paid_state(2000, 500, 100), "part_paid")
		self.assertEqual(po.paid_state(2000, 2000, 100), "unpaid")

	def test_late_means_past_the_promise_and_not_delivered(self):
		self.assertTrue(po.is_late("2026-11-17", "2026-11-18", po.STAGE_READY))
		self.assertTrue(po.is_late(date(2026, 11, 1), date(2026, 11, 18), po.STAGE_ORDERED))
		self.assertFalse(po.is_late("2026-11-18", "2026-11-18", po.STAGE_READY), "due today is not late")
		self.assertFalse(po.is_late("2026-11-01", "2026-11-18", po.STAGE_DELIVERED))
		self.assertFalse(po.is_late(None, "2026-11-18", po.STAGE_ORDERED))
		self.assertFalse(po.is_late("", "2026-11-18", po.STAGE_ORDERED))

	def test_an_open_quotation(self):
		today, since = "2026-11-18", "2026-08-20"
		# prod's shape: a draft mirrored from QuickBooks, no Valid Till
		self.assertTrue(po.is_open_quotation("Draft", 0, None, "2026-11-17", since, today))
		self.assertTrue(po.is_open_quotation("Draft", 0, None, since, since, today))
		self.assertFalse(po.is_open_quotation("Draft", 0, None, "2026-08-19", since, today))
		self.assertFalse(po.is_open_quotation("Draft", 0, None, None, since, today))
		# a Valid Till decides when there is one, whatever the date
		self.assertTrue(po.is_open_quotation("Open", 1, "2026-11-18", "2025-01-01", since, today))
		self.assertFalse(po.is_open_quotation("Open", 1, "2026-11-17", "2026-11-17", since, today))
		for status in ("Lost", "Ordered", "Expired", "Cancelled"):
			with self.subTest(status=status):
				self.assertFalse(po.is_open_quotation(status, 1, "2027-01-01", "2026-11-17", since, today))
		self.assertFalse(po.is_open_quotation("Draft", 2, None, "2026-11-17", since, today))
		self.assertTrue(
			po.is_open_quotation("Draft", 0, None, date(2026, 11, 17), date(2026, 8, 20), date(2026, 11, 18))
		)

	def test_an_open_opportunity(self):
		for status in (
			"Open",
			"Qualification",
			"Needs Analysis",
			"Negotiation/Review",
			"On Hold",
			"Quotation",
		):
			with self.subTest(status=status):
				self.assertTrue(po.is_open_opportunity(status))
		for status in ("Closed Won", "Lost", "Closed", "Converted"):
			with self.subTest(status=status):
				self.assertFalse(po.is_open_opportunity(status))

	def test_win_rate_is_won_over_decided(self):
		self.assertIsNone(po.win_rate(0, 0))
		self.assertEqual(po.win_rate(7, 0), 100)  # prod's Products stream on 2026-11-18
		self.assertEqual(po.win_rate(1, 2), 33)
		self.assertEqual(po.win_rate(2, 1), 67)
		self.assertEqual(po.win_rate(None, "3"), 0)

	def test_the_win_rate_counts_won_and_lost_as_the_value_stream_report_does(self):
		tree = ast.parse(REPORT.read_text(encoding="utf-8"))
		found = {}
		for node in tree.body:
			if (
				isinstance(node, ast.Assign)
				and len(node.targets) == 1
				and isinstance(node.targets[0], ast.Name)
			):
				if node.targets[0].id in ("WON_STATUSES", "LOST_STATUSES"):
					found[node.targets[0].id] = ast.literal_eval(node.value)
		self.assertEqual(found.get("WON_STATUSES"), po.WON_STATUSES)
		self.assertEqual(found.get("LOST_STATUSES"), po.LOST_STATUSES)

	def test_component_state(self):
		self.assertEqual(po.component_state(0, 0), "out")
		self.assertEqual(po.component_state(-2, 5), "out")
		self.assertEqual(po.component_state(None, None), "out")
		self.assertEqual(po.component_state(3, 5), "low")
		self.assertEqual(po.component_state(5, 5), "ok")
		self.assertEqual(po.component_state(71, 0), "ok", "no reorder level set: only zero is short")

	def test_the_estop_components_are_the_configurators_group(self):
		self.assertEqual(po.COMPONENT_GROUPS, {po.LINE_ESTOPS: ("E-Stop Components",)})


class TestTheBlockAgrees(unittest.TestCase):
	"""The script and the shell name the same lines and stages the server sends."""

	def test_the_line_chips_are_the_servers_lines(self):
		self.assertEqual(tuple(_js_list("PRODUCT_LINES")), po.LINES)
		chips = re.findall(r'<button type="button" class="pd-lchip" data-line="([^"]*)"', BLOCK_HTML)
		self.assertEqual(chips, ["", *po.LINES])
		counts = re.findall(r'data-line-count="([^"]*)"', BLOCK_HTML)
		self.assertEqual(counts, chips)

	def test_the_boards_stages_are_the_servers_stages(self):
		self.assertEqual(tuple(_js_list("PRODUCT_STAGES")), po.STAGES)
		words = re.search(r"const STAGE_WORDS = \{([^}]*)\}", BLOCK_JS).group(1)
		self.assertEqual(dict(re.findall(r'(\w+): "([^"]+)"', words)), po.STAGE_LABELS)

	def test_the_component_states_the_script_draws_are_the_rules_states(self):
		words = re.search(r"const COMPONENT_WORDS = \{([^}]*)\}", BLOCK_JS).group(1)
		self.assertEqual(sorted(re.findall(r"(\w+): \[", words)), ["low", "out"])
		paid = BLOCK_JS[BLOCK_JS.index("const PAID_WORDS = {") :]
		paid = paid[: paid.index("};")]
		self.assertEqual(
			sorted(re.findall(r"(\w+): \[", paid)), ["not_invoiced", "paid", "part_paid", "unpaid"]
		)


