"""Idempotent custom-field provisioning for the Product Configurator.

Registered in ``after_migrate`` (hooks.py). Insert-only, mirroring
``device_management.setup``: a field that already exists is left exactly as it
is, so a label somebody changed on the site survives a migrate.

* ``Item.custom_source_configuration`` — the provenance field the generation
  engine stamps on configured-product Items: it marks an Item as
  configurator-owned so a regenerate can safely reuse it, and a hand-made Item
  with a colliding code is never touched.
* ``Quotation Item.custom_product_configuration`` and the same field on
  ``Sales Order Item`` (v1.824.0) — the configuration a line was quoted from.
  ``quoting.create_quotation`` sets it on the Quotation line; ERPNext's Make
  Sales Order copies every same-named field across, so the Sales Order line
  carries it too, which is how the Work Order step will find the exact
  configuration a unit is built to. Not ``no_copy`` for that reason. The Item
  alone cannot say: two configurations with the same part number share one
  Item.
"""

import frappe
from frappe.custom.doctype.custom_field.custom_field import create_custom_fields

_LINE_FIELD = {
	"fieldname": "custom_product_configuration",
	"label": "Product Configuration",
	"fieldtype": "Link",
	"options": "Product Configuration",
	"insert_after": "item_name",
	"read_only": 1,
	"description": "The Product Configuration this line was quoted from.",
}

FIELDS = {
	"Item": [
		{
			"fieldname": "custom_source_configuration",
			"label": "Source Configuration",
			"fieldtype": "Link",
			"options": "Product Configuration",
			"insert_after": "description",
			"read_only": 1,
			"hidden": 1,
			"no_copy": 1,
			"description": "Set when this Item was generated by the Product Configurator.",
		}
	],
	"Quotation Item": [dict(_LINE_FIELD)],
	"Sales Order Item": [dict(_LINE_FIELD)],
}


def create_configurator_item_fields():
	"""``after_migrate`` entry point: every field in :data:`FIELDS` that a site lacks."""
	missing = {}
	for doctype, fields in FIELDS.items():
		if not frappe.db.exists("DocType", doctype):
			continue
		meta = frappe.get_meta(doctype)
		todo = [field for field in fields if not meta.has_field(field["fieldname"])]
		if todo:
			missing[doctype] = todo
	if missing:
		create_custom_fields(missing, update=True)
